//! Processing parameters shared by the Python reference and the Rust port.
//!
//! Port of `python/optflow_ref/config.py`; that file is the specification. Field names, defaults,
//! JSON keys, the `from_json` checks (in the same order) and the `validate` rules and messages are
//! identical, so both implementations reject the same configs with the same message, and
//! [`Config::to_json`] writes the text of Python's `json.dumps(..., indent=2)`, floats spelled
//! like `float.__repr__` (`1e-07`, `1e+16`, 17 digit shortest reprs; `NaN` and `Infinity` for the
//! non-finite ones). Deviations: the JSON reader is a strict JSON parser (Python's `json` also
//! reads the literals `NaN` and `Infinity` and an overflowing `1e999`; they are syntax errors
//! here), and an integer field takes the range `i64::MIN..=u64::MAX` only: a larger integer is
//! rejected as "must be an integer in range", where Python holds any `int`. As in Python, `-0` is
//! the integer 0 (and `0.0` in a float field), and `2.0` or `1e3` are floats, not integers.

use std::cell::RefCell;
use std::collections::VecDeque;
use std::fmt;

use serde::de::{self, DeserializeSeed, Deserializer, MapAccess, SeqAccess, Visitor};
use serde::{Deserialize, Serialize};

/// Why a [`Config`] could not be read or is not usable.
#[derive(Clone, Debug, PartialEq, thiserror::Error)]
pub enum ConfigError {
    /// The text is not valid JSON (the wording is serde_json's, not Python's).
    #[error("invalid config JSON: {0}")]
    Json(String),
    /// The JSON is valid but not an object.
    #[error("config must be a JSON object")]
    NotAnObject,
    /// The JSON has keys that are not `Config` fields (sorted, like Python's message).
    #[error("unknown config keys: {}", format_keys(.0))]
    UnknownKeys(Vec<String>),
    /// A value has the wrong JSON type (message as in Python's `from_json`).
    #[error("{0}")]
    BadType(String),
    /// A parameter is outside its allowed range (message as in Python's `validate`).
    #[error("{0}")]
    Invalid(String),
}

/// Python list repr of the keys, e.g. `['a', 'b']`.
fn format_keys(keys: &[String]) -> String {
    let items: Vec<String> = keys.iter().map(|k| py_str_repr(k)).collect();
    format!("[{}]", items.join(", "))
}

/// The Unicode format characters (category Cf, Unicode 15) as inclusive ranges; Rust's standard
/// library has no general category lookup.
const FORMAT_CHARS: [(u32, u32); 21] = [
    (0x00AD, 0x00AD),
    (0x0600, 0x0605),
    (0x061C, 0x061C),
    (0x06DD, 0x06DD),
    (0x070F, 0x070F),
    (0x0890, 0x0891),
    (0x08E2, 0x08E2),
    (0x180E, 0x180E),
    (0x200B, 0x200F),
    (0x202A, 0x202E),
    (0x2060, 0x2064),
    (0x2066, 0x206F),
    (0xFEFF, 0xFEFF),
    (0xFFF9, 0xFFFB),
    (0x110BD, 0x110BD),
    (0x110CD, 0x110CD),
    (0x13430, 0x1343F),
    (0x1BCA0, 0x1BCA3),
    (0x1D173, 0x1D17A),
    (0xE0001, 0xE0001),
    (0xE0020, 0xE007F),
];

/// The private-use planes and block (category Co) as inclusive ranges.
const PRIVATE_USE: [(u32, u32); 3] = [(0xE000, 0xF8FF), (0xF0000, 0xFFFFD), (0x100000, 0x10FFFD)];

/// The unassigned code points (category Cn) of the Unicode database of the Python that is the
/// reference (Unicode 15.0), generated by `rust/scripts/gen_unicode_cn.py`.
mod unicode_cn;

/// Python's `str.isprintable` for one character: not printable are the control characters (Cc),
/// format characters (Cf), private use (Co), unassigned code points (Cn, as of the Unicode version
/// of [`unicode_cn`]) and the separators (Zs, Zl, Zp) other than the plain space.
/// `char::is_whitespace` is exactly Zs, Zl, Zp and the control characters among U+0009 to U+000D
/// and U+0085.
fn is_printable(c: char) -> bool {
    if c == ' ' {
        return true;
    }
    let n = u32::from(c);
    let within = |ranges: &[(u32, u32)]| ranges.iter().any(|&(lo, hi)| (lo..=hi).contains(&n));
    let unassigned = unicode_cn::UNASSIGNED
        .binary_search_by(|&(lo, hi)| {
            if hi < n {
                std::cmp::Ordering::Less
            } else if lo > n {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok();
    !(c.is_control()
        || c.is_whitespace()
        || within(&FORMAT_CHARS)
        || within(&PRIVATE_USE)
        || unassigned)
}

/// Python's `repr` of a `str`: single quotes unless the text has a `'` and no `"`. Characters
/// Python calls unprintable (see [`is_printable`]) are escaped as `\xhh`, `\uhhhh` or `\Uhhhhhhhh`.
///
/// Public for the `optflow` binary's messages, not part of the library's interface.
#[doc(hidden)]
pub fn py_str_repr(s: &str) -> String {
    let quote = if s.contains('\'') && !s.contains('"') {
        '"'
    } else {
        '\''
    };
    let mut out = String::with_capacity(s.len() + 2);
    out.push(quote);
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if c == quote => {
                out.push('\\');
                out.push(c);
            }
            c if !is_printable(c) => {
                let n = u32::from(c);
                if n < 0x100 {
                    out.push_str(&format!("\\x{n:02x}"));
                } else if n < 0x10000 {
                    out.push_str(&format!("\\u{n:04x}"));
                } else {
                    out.push_str(&format!("\\U{n:08x}"));
                }
            }
            c => out.push(c),
        }
    }
    out.push(quote);
    out
}

/// Python's `repr` of a `float`: the shortest digits that read back exactly, positional notation
/// for decimal exponents -5 to 15 and `1e+16` style beyond, always with a `.0` or exponent.
fn py_float_repr(x: f64) -> String {
    if x.is_nan() {
        return "nan".to_string();
    }
    if x.is_infinite() {
        return if x > 0.0 { "inf" } else { "-inf" }.to_string();
    }
    // Rust's `{:e}` also prints the shortest round-trip digits, e.g. "1.25e-7". Where two such
    // digit strings are equally near the value (it lies exactly halfway between them) it takes the
    // upper one, but Python takes the one with the even last digit, as the exact formatting
    // `{:.Ne}` does: with the digit count of the shortest form that is the nearest string of that
    // length, which is the answer whenever it reads back as `x`.
    let shortest = format!("{:e}", x.abs());
    let count = shortest
        .split('e')
        .next()
        .map_or(1, |m| m.len() - m.matches('.').count());
    let nearest = format!("{:.*e}", count - 1, x.abs());
    let sci = if nearest.parse::<f64>() == Ok(x.abs()) {
        nearest
    } else {
        shortest
    };
    let (mantissa, exp) = sci.split_once('e').expect("LowerExp has an exponent");
    let exp: i32 = exp.parse().expect("LowerExp exponent is an integer");
    let digits: String = mantissa.chars().filter(|&c| c != '.').collect();
    let sign = if x.is_sign_negative() { "-" } else { "" };
    // value = 0.DIGITS * 10^point
    let point = exp + 1;
    let body = if point <= -4 || point > 16 {
        let (first, rest) = digits.split_at(1);
        let frac = if rest.is_empty() {
            String::new()
        } else {
            format!(".{rest}")
        };
        format!(
            "{first}{frac}e{}{:02}",
            if exp < 0 { '-' } else { '+' },
            exp.abs()
        )
    } else if point <= 0 {
        format!("0.{}{digits}", "0".repeat(point.unsigned_abs() as usize))
    } else if point as usize >= digits.len() {
        format!("{digits}{}.0", "0".repeat(point as usize - digits.len()))
    } else {
        let (int, frac) = digits.split_at(point as usize);
        format!("{int}.{frac}")
    };
    format!("{sign}{body}")
}

/// A float as `json.dumps` writes it: `float.__repr__`, and `NaN` / `Infinity` / `-Infinity`
/// (which are not JSON) for the non-finite ones.
fn json_float(x: f64) -> String {
    if x.is_nan() {
        "NaN".to_string()
    } else if x.is_infinite() {
        if x > 0.0 { "Infinity" } else { "-Infinity" }.to_string()
    } else {
        py_float_repr(x)
    }
}

/// A string as `json.dumps` writes it (`ensure_ascii`: non-ASCII as `\uXXXX`, surrogate pairs
/// beyond the BMP).
fn json_string(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '\u{8}' => out.push_str("\\b"),
            '\u{c}' => out.push_str("\\f"),
            c if (c as u32) < 0x20 || (c as u32) > 0x7f => {
                let mut buf = [0u16; 2];
                for unit in c.encode_utf16(&mut buf) {
                    out.push_str(&format!("\\u{unit:04x}"));
                }
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// A JSON value with objects kept in text order (Python's dict order; `serde_json::Value` sorts).
/// Integers and floats are told apart like Python's `int` and `float`: by how the number is
/// written (`2.0`, `1e3` are floats), see [`NumberTokens`].
#[derive(Clone, Debug, PartialEq)]
enum Json {
    Null,
    Bool(bool),
    Int(i128),
    /// An integer beyond the `i128` range, as the (canonical) decimal text.
    BigInt(String),
    Float(f64),
    Str(String),
    List(Vec<Json>),
    /// A repeated key keeps its first position and its last value, like a Python dict.
    Object(Vec<(String, Json)>),
}

/// The number tokens of a JSON text in document order, as written. serde_json hands numbers to a
/// visitor as `i64`, `u64` or `f64` and so forgets that `-0` or a 30 digit integer was an `int` in
/// the sense of Python (`-0` arrives as the float `-0.0`, an integer above 2^64 as a float), while
/// the text still tells. A number visited is the next token of this queue.
struct NumberTokens<'t>(RefCell<VecDeque<&'t str>>);

impl<'t> NumberTokens<'t> {
    /// Scans `text`: strings are skipped, a number starts at `-` or a digit and runs over the
    /// characters a JSON number is made of. For text that is not valid JSON the queue is
    /// meaningless, but the parser reports that.
    fn scan(text: &'t str) -> Self {
        let bytes = text.as_bytes();
        let mut tokens = VecDeque::new();
        let mut i = 0;
        while i < bytes.len() {
            match bytes[i] {
                b'"' => {
                    i += 1;
                    while i < bytes.len() && bytes[i] != b'"' {
                        i += if bytes[i] == b'\\' { 2 } else { 1 };
                    }
                    i += 1;
                }
                b'-' | b'0'..=b'9' => {
                    let start = i;
                    while i < bytes.len()
                        && matches!(bytes[i], b'-' | b'+' | b'.' | b'e' | b'E' | b'0'..=b'9')
                    {
                        i += 1;
                    }
                    tokens.push_back(&text[start..i]);
                }
                _ => i += 1,
            }
        }
        Self(RefCell::new(tokens))
    }

    /// The value of the number just visited: an integer if its token has no fraction or exponent
    /// (serde_json's reading `natural` is kept for the floats and if the queue ran dry).
    fn value(&self, natural: Json) -> Json {
        match self.0.borrow_mut().pop_front() {
            Some(t) if !t.contains(['.', 'e', 'E']) => t
                .parse::<i128>()
                .map_or_else(|_| Json::BigInt(t.to_string()), Json::Int),
            _ => natural,
        }
    }
}

/// Reads one JSON value as a [`Json`], taking the kind of each number from `tokens`.
struct JsonSeed<'a, 't>(&'a NumberTokens<'t>);

impl<'de> DeserializeSeed<'de> for JsonSeed<'_, '_> {
    type Value = Json;

    fn deserialize<D: Deserializer<'de>>(self, d: D) -> Result<Json, D::Error> {
        struct V<'a, 't>(&'a NumberTokens<'t>);
        impl<'de> Visitor<'de> for V<'_, '_> {
            type Value = Json;
            fn expecting(&self, f: &mut fmt::Formatter) -> fmt::Result {
                f.write_str("any JSON value")
            }
            fn visit_unit<E>(self) -> Result<Json, E> {
                Ok(Json::Null)
            }
            fn visit_bool<E>(self, v: bool) -> Result<Json, E> {
                Ok(Json::Bool(v))
            }
            fn visit_i64<E>(self, v: i64) -> Result<Json, E> {
                Ok(self.0.value(Json::Int(i128::from(v))))
            }
            fn visit_u64<E>(self, v: u64) -> Result<Json, E> {
                Ok(self.0.value(Json::Int(i128::from(v))))
            }
            fn visit_f64<E>(self, v: f64) -> Result<Json, E> {
                Ok(self.0.value(Json::Float(v)))
            }
            fn visit_str<E: de::Error>(self, v: &str) -> Result<Json, E> {
                Ok(Json::Str(v.to_string()))
            }
            fn visit_seq<A: SeqAccess<'de>>(self, mut seq: A) -> Result<Json, A::Error> {
                let mut items = Vec::new();
                while let Some(item) = seq.next_element_seed(JsonSeed(self.0))? {
                    items.push(item);
                }
                Ok(Json::List(items))
            }
            fn visit_map<A: MapAccess<'de>>(self, mut map: A) -> Result<Json, A::Error> {
                let mut entries: Vec<(String, Json)> = Vec::new();
                while let Some(k) = map.next_key::<String>()? {
                    let v = map.next_value_seed(JsonSeed(self.0))?;
                    match entries.iter_mut().find(|(ek, _)| *ek == k) {
                        Some(slot) => slot.1 = v,
                        None => entries.push((k, v)),
                    }
                }
                Ok(Json::Object(entries))
            }
        }
        d.deserialize_any(V(self.0))
    }
}

/// Parses `text` as JSON (the strict syntax of serde_json) into a [`Json`].
fn parse_json(text: &str) -> Result<Json, ConfigError> {
    let tokens = NumberTokens::scan(text);
    let mut de = serde_json::Deserializer::from_str(text);
    let json = JsonSeed(&tokens)
        .deserialize(&mut de)
        .map_err(|e| ConfigError::Json(e.to_string()))?;
    de.end().map_err(|e| ConfigError::Json(e.to_string()))?;
    Ok(json)
}

impl Json {
    /// Python's `repr` of the value the JSON text becomes (`None`, `True`, `[1, 'a']`, ...).
    fn py_repr(&self) -> String {
        match self {
            Json::Null => "None".to_string(),
            Json::Bool(b) => if *b { "True" } else { "False" }.to_string(),
            Json::Int(n) => n.to_string(),
            Json::BigInt(text) => text.clone(),
            Json::Float(x) => py_float_repr(*x),
            Json::Str(s) => py_str_repr(s),
            Json::List(items) => {
                let items: Vec<String> = items.iter().map(Json::py_repr).collect();
                format!("[{}]", items.join(", "))
            }
            Json::Object(entries) => {
                let items: Vec<String> = entries
                    .iter()
                    .map(|(k, v)| format!("{}: {}", py_str_repr(k), v.py_repr()))
                    .collect();
                format!("{{{}}}", items.join(", "))
            }
        }
    }

    /// The value as a float if it is a number (not a bool), like `float(v)` after `_is_number`.
    fn as_number(&self) -> Option<f64> {
        match self {
            Json::Int(n) => Some(*n as f64),
            // correctly rounded, `inf` beyond the f64 range (the finiteness rule of `validate` speaks)
            Json::BigInt(text) => text.parse().ok(),
            Json::Float(x) => Some(*x),
            _ => None,
        }
    }
}

/// The error for `key` holding `v`, which is not `what` (Python: "config key 'k' must be ..., got v").
fn bad_type(key: &str, what: &str, v: &Json) -> ConfigError {
    ConfigError::BadType(format!(
        "config key {} must be {what}, got {}",
        py_str_repr(key),
        v.py_repr()
    ))
}

/// An integer field: Python accepts any `int` that is not a `bool`; here the 64 bit range
/// `i64::MIN..=u64::MAX` (a larger integer is reported as out of range, not as "not an integer").
fn int_field(key: &str, v: &Json) -> Result<i128, ConfigError> {
    match v {
        Json::Int(n) if (i128::from(i64::MIN)..=i128::from(u64::MAX)).contains(n) => Ok(*n),
        Json::Int(_) | Json::BigInt(_) => Err(bad_type(key, "an integer in range", v)),
        _ => Err(bad_type(key, "an integer", v)),
    }
}

/// An integer as a `usize`. A negative value becomes 0 (and a value above the range, which
/// `int_field` rules out for 64 bit `usize`, would saturate): every `validate` rule on these
/// fields gives the same verdict for the stored value as for the original (they all test `< 1`,
/// `< 5`, `< 16` or "not 1 or 2").
fn to_usize(n: i128) -> usize {
    usize::try_from(n.max(0)).unwrap_or(usize::MAX)
}

/// As [`to_usize`], for `shape_order`: a value above `u32::MAX` saturates.
fn to_u32(n: i128) -> u32 {
    u32::try_from(n.max(0)).unwrap_or(u32::MAX)
}

/// An integer as an `i64` (above `i64::MAX` it saturates: every rule on these fields is a sign or
/// an upper bound).
fn to_i64(n: i128) -> i64 {
    i64::try_from(n).unwrap_or(i64::MAX)
}

/// A string field.
fn str_field(key: &str, v: &Json) -> Result<String, ConfigError> {
    match v {
        Json::Str(s) => Ok(s.clone()),
        _ => Err(bad_type(key, "a string", v)),
    }
}

/// A boolean field.
fn bool_field(key: &str, v: &Json) -> Result<bool, ConfigError> {
    match v {
        Json::Bool(b) => Ok(*b),
        _ => Err(bad_type(key, "true or false", v)),
    }
}

/// A float field: Python accepts an `int` or a `float` that is not a `bool`.
fn float_field(key: &str, v: &Json) -> Result<f64, ConfigError> {
    v.as_number().ok_or_else(|| bad_type(key, "a number", v))
}

/// A list of numbers (`scales`).
fn list_field(key: &str, v: &Json) -> Result<Vec<f64>, ConfigError> {
    match v {
        Json::List(items) => items
            .iter()
            .map(Json::as_number)
            .collect::<Option<Vec<f64>>>(),
        _ => None,
    }
    .ok_or_else(|| bad_type(key, "a list of numbers", v))
}

/// Processing parameters. `Default` gives the values of Python's `Config()`.
///
/// Read a config from text with [`Config::from_json`]: it checks the types and runs
/// [`validate`](Config::validate), with Python's messages. The `Deserialize` derive is plain
/// serde: it checks nothing (not even the ranges), so call `validate` on what it returns.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields, default)]
pub struct Config {
    // coarse stage: windowed phase-only correlation on a grid
    pub grid_step: usize,
    pub poc_win: usize,
    /// Expected max displacement [px]; sets the pyramid depth.
    pub max_disp: f64,
    pub poc_peak_min: f64,
    pub median_thresh: f64,
    // fine stage: local phase of a complex Gabor bank
    pub lam: f64,
    /// Filter wavelengths are `lam * scales`.
    pub scales: Vec<f64>,
    pub n_orient: usize,
    pub bandwidth: f64,
    /// DC cut of the filter bank: high-pass width = `dc_cut * lam * max(scales) / (2 pi)`.
    pub dc_cut: f64,
    pub sigma_w: f64,
    /// Local displacement model: 1 affine, 2 quadratic.
    pub shape_order: u32,
    pub sigma_s: f64,
    pub outer_iters: usize,
    pub inner_iters: usize,
    // validity and strain
    pub conf_min: f64,
    /// Pixels closer than this to any invalid pixel are set invalid. `< 0`: automatic (3 x the
    /// spatial sigma of the longest-wavelength filter); `0`: off.
    pub edge_guard: f64,
    /// Only invalid regions at least this large [px^2] are guarded (plus the ROI exterior).
    /// `< 0`: automatic, 2 x (longest wavelength)^2.
    pub edge_guard_min_area: f64,
    /// [rad] `conf = texture * exp(-(phase residual / phase_tol)^2)`.
    pub phase_tol: f64,
    pub strain_win: usize,
    // sequences
    pub ref_update_conf: f64,
    /// Sequence mode: `"chain"` or `"hybrid"` (direct-first with a spatially gated adjacent-frame
    /// fallback, report 2026-11-02-hybrid-sequence-phase1-report.md sections v2 and v3).
    pub seq_mode: String,
    /// Hybrid: most consecutive frames a pixel is carried by the adjacent leg.
    pub fb_max: i64,
    /// Hybrid gate: half-width [px] of the window of direct-good pixels (`< 0`: 4 `sigma_w`).
    pub fb_radius: f64,
    /// Hybrid gate: direct-good pixels needed in the window (0: gate off).
    pub fb_min_support: i64,
    /// Hybrid: agreement tolerance [px] of the gate and of the re-acquisition.
    pub fb_tol: f64,
    /// Temporal averaging front-end of `seq`: each sampled frame is the mean of the `2 tavg + 1`
    /// frames around it (0: off).
    pub tavg: i64,
    /// Align the neighbours to the centre frame before averaging.
    pub tavg_align: bool,
    /// Motion model of the alignment: `"affine"` or `"dense"`.
    pub tavg_model: String,
    /// Keep the low pixels of the pre-warp of outer iteration `K` for every later outer iteration
    /// (prototype of 2026-11-03-convergence-fixes.md; the environment variable
    /// `OPTFLOW_PREWARP_FREEZE_AT` does the same when this is 0). 0: off. Rust only: the Python
    /// reference does not implement it.
    pub prewarp_freeze_at: i64,
    /// Crack handling (experimental):
    /// `"off"` or `"xdic"` ([`crate::xdic`]). `"xdic"` detects crack lines as jumps of the baseline
    /// field and re-solves the pixels within `xdic_RB` px of a line per side of it. Python's
    /// stage-1/2 crack keys (`crack_split`, `crack_out`, `crack_sides`, ...) are not adopted and stay
    /// rejected as unknown keys. Left out of [`Config::to_json`] while at the default, like Python.
    pub crack_model: String,
    /// Half width `R_B` [px] of the strip around a crack line that is solved per side (`< 0`:
    /// automatic, [`Config::xdic_rb_px`]). JSON key `xdic_RB`.
    #[serde(rename = "xdic_RB")]
    pub xdic_rb: f64,
    /// Number of geometry updates of the crack lines (one after every second outer iteration).
    pub xdic_iters: i64,
}

