/// True for the powers of two that are at least 16 (`v >= 16` and exactly one bit set).
pub fn is_pow2_at_least_16(v: usize) -> bool {
    v >= 16 && v & (v - 1) == 0
}

/// Python's `min()` of a non-empty list: the first element that no later one is strictly below.
/// With a NaN this differs from `f64::min`, and `validate` has to agree with Python there.
fn py_min(xs: &[f64]) -> f64 {
    xs.iter()
        .copied()
        .reduce(|m, x| if x < m { x } else { m })
        .expect("py_min needs a non-empty list")
}

impl Config {
    /// Checks the parameter ranges, with the rules, order and messages of Python's `validate`.
    ///
    /// The comparisons are written the way Python writes them (`x <= 0`, not `!(x > 0)`), so a NaN
    /// passes the range rules and is then rejected by the finiteness rules, as in Python.
    pub fn validate(&self) -> Result<(), ConfigError> {
        let invalid = |msg: &str| Err(ConfigError::Invalid(msg.to_string()));
        if self.seq_mode != "chain" && self.seq_mode != "hybrid" {
            return invalid(&format!(
                "seq_mode must be 'chain' or 'hybrid', got {}",
                py_str_repr(&self.seq_mode)
            ));
        }
        if self.scales.is_empty() {
            return invalid("scales must not be empty");
        }
        if !is_pow2_at_least_16(self.poc_win) {
            return invalid("poc_win must be a power of two >= 16");
        }
        if self.grid_step < 1 || self.strain_win < 5 || self.strain_win.is_multiple_of(2) {
            return invalid("grid_step >= 1 and strain_win odd >= 5 required");
        }
        if self.dc_cut <= 0.0 {
            return invalid("dc_cut must be positive");
        }
        if self.phase_tol <= 0.0 {
            return invalid("phase_tol must be positive");
        }
        if self.shape_order != 1 && self.shape_order != 2 {
            return invalid("shape_order must be 1 or 2");
        }
        if self.lam * py_min(&self.scales) < 3.0 || self.sigma_w <= 0.0 || self.sigma_s <= 0.0 {
            return invalid(
                "shortest wavelength lam*min(scales) must be >= 3 px; sigmas must be positive",
            );
        }
        let floats = [
            ("max_disp", self.max_disp),
            ("poc_peak_min", self.poc_peak_min),
            ("median_thresh", self.median_thresh),
            ("lam", self.lam),
            ("bandwidth", self.bandwidth),
            ("dc_cut", self.dc_cut),
            ("sigma_w", self.sigma_w),
            ("sigma_s", self.sigma_s),
            ("conf_min", self.conf_min),
            ("edge_guard", self.edge_guard),
            ("edge_guard_min_area", self.edge_guard_min_area),
            ("phase_tol", self.phase_tol),
            ("ref_update_conf", self.ref_update_conf),
        ];
        for (name, v) in floats {
            if !v.is_finite() {
                return invalid(&format!("{name} must be a finite number"));
            }
        }
        if !self.scales.iter().all(|x| x.is_finite()) {
            return invalid("scales must be finite numbers");
        }
        if self.bandwidth <= 0.0 || self.max_disp <= 0.0 || self.median_thresh <= 0.0 {
            return invalid("bandwidth, max_disp and median_thresh must be positive");
        }
        if self.n_orient < 1 || self.outer_iters < 1 || self.inner_iters < 1 {
            return invalid("n_orient, outer_iters and inner_iters must be >= 1");
        }
        if !(0.0..=1.0).contains(&self.conf_min) || !(0.0..=1.0).contains(&self.poc_peak_min) {
            return invalid("conf_min and poc_peak_min must lie in [0, 1]");
        }
        if self.fb_max < 0 {
            return invalid("fb_max must be >= 0");
        }
        if !self.fb_radius.is_finite()
            || !self.fb_tol.is_finite()
            || self.fb_tol <= 0.0
            || self.fb_radius == 0.0
        {
            return invalid(
                "fb_radius must be finite and nonzero (negative: 4 sigma_w), fb_tol finite and positive",
            );
        }
        if self.fb_min_support < 0 || self.tavg < 0 || self.tavg > 64 {
            return invalid("fb_min_support must be >= 0 and tavg in [0, 64]");
        }
        if self.tavg_model != "affine" && self.tavg_model != "dense" {
            return invalid(&format!(
                "tavg_model must be 'affine' or 'dense', got {}",
                py_str_repr(&self.tavg_model)
            ));
        }
        if self.prewarp_freeze_at < 0 {
            return invalid("prewarp_freeze_at must be >= 0");
        }
        if self.crack_model != "off" && self.crack_model != "xdic" {
            return invalid(&format!(
                "crack_model must be 'off' or 'xdic', got {}",
                py_str_repr(&self.crack_model)
            ));
        }
        if !self.xdic_rb.is_finite() || self.xdic_rb == 0.0 || self.xdic_rb > 256.0 {
            return invalid("xdic_RB must be finite, nonzero and <= 256 (negative: automatic)");
        }
        if !(0..=8).contains(&self.xdic_iters) {
            return invalid("xdic_iters must be an integer in [0, 8]");
        }
        // upper bounds that keep the memory per tile sane (an absurd value would abort on
        // allocation); last, so every message above keeps its place. The product saturates where
        // Python's int grows: the verdict is the same.
        if self.n_orient.saturating_mul(self.scales.len()) > 64
            || self.sigma_w > 256.0
            || self.sigma_s > 256.0
            || self.strain_win > 255
            || self.poc_win > 1024
        {
            return invalid(
                "at most 64 filters (n_orient * len(scales)); sigma_w, sigma_s <= 256, \
                 strain_win <= 255 and poc_win <= 1024 required",
            );
        }
        // the grid step enters the crop alignment `grid_step * 2^L`, the guard sets the tile margin:
        // both bounded so that no product or sum of them can overflow a 64-bit size; after the
        // bounds, so their message keeps its place
        if self.grid_step > 4096 || self.edge_guard_px() > 256.0 {
            return invalid(
                "grid_step <= 4096 and an edge guard (edge_guard, or the automatic one from lam, \
                 scales and bandwidth) <= 256 px required",
            );
        }
        Ok(())
    }

    /// The automatic guard distance [px]: 3 x the spatial sigma of the longest-wavelength filter,
    /// the reach of a discontinuity into the phase. Independent of the `edge_guard` the user
    /// chose. Needs non-empty `scales` (`validate` checks this).
    pub fn auto_edge_guard_px(&self) -> f64 {
        let max_scale = self
            .scales
            .iter()
            .copied()
            .fold(f64::NEG_INFINITY, f64::max);
        3.0 * self.lam * max_scale / (2.0 * std::f64::consts::PI * self.bandwidth)
    }

    /// Resolved guard distance in pixels. Needs non-empty `scales` when `edge_guard < 0`
    /// (`validate` checks this).
    pub fn edge_guard_px(&self) -> f64 {
        if self.edge_guard >= 0.0 {
            return self.edge_guard;
        }
        self.auto_edge_guard_px()
    }

    /// Resolved minimum area [px^2] of an invalid region that gets a guard band. Needs non-empty
    /// `scales` when `edge_guard_min_area < 0` (`validate` checks this).
    pub fn edge_guard_min_area_px(&self) -> f64 {
        if self.edge_guard_min_area >= 0.0 {
            return self.edge_guard_min_area;
        }
        let max_scale = self
            .scales
            .iter()
            .copied()
            .fold(f64::NEG_INFINITY, f64::max);
        2.0 * (self.lam * max_scale).powi(2)
    }

    /// Resolved `R_B` [px] of `crack_model = "xdic"`: the half width of the strip around a crack
    /// line that is solved per side (`xdic_RB` if positive, else the automatic edge guard plus
    /// `4 sigma_w`, 28 px at the defaults).
    pub fn xdic_rb_px(&self) -> f64 {
        if self.xdic_rb > 0.0 {
            self.xdic_rb
        } else {
            self.auto_edge_guard_px() + 4.0 * self.sigma_w
        }
    }

    /// Whether `crack_model` is `"xdic"`.
    pub fn is_xdic(&self) -> bool {
        self.crack_model == "xdic"
    }

    /// Resolved half-width [px] of the support window of the hybrid fallback gate.
    pub fn fb_radius_px(&self) -> f64 {
        if self.fb_radius > 0.0 {
            self.fb_radius
        } else {
            4.0 * self.sigma_w
        }
    }

    /// Whether `seq_mode` is `"hybrid"`.
    pub fn is_hybrid(&self) -> bool {
        self.seq_mode == "hybrid"
    }

    /// Parses a JSON object like Python's `from_json`: missing keys keep their defaults, unknown
    /// keys are an error, then each value is type-checked in text order (an integer field needs an
    /// integer, not `2.5` or `true`; a float field any number, ints included; `scales` a list of
    /// numbers) and finally [`validate`](Self::validate) runs.
    pub fn from_json(s: &str) -> Result<Self, ConfigError> {
        let Json::Object(entries) = parse_json(s)? else {
            return Err(ConfigError::NotAnObject);
        };
        let known =
            serde_json::to_value(Self::default()).map_err(|e| ConfigError::Json(e.to_string()))?;
        let known = known.as_object().expect("Config serialises to an object");
        let mut unknown: Vec<String> = entries
            .iter()
            .map(|(k, _)| k)
            .filter(|k| !known.contains_key(*k))
            .cloned()
            .collect();
        if !unknown.is_empty() {
            unknown.sort();
            return Err(ConfigError::UnknownKeys(unknown));
        }
        let mut cfg = Self::default();
        for (key, v) in &entries {
            match key.as_str() {
                "grid_step" => cfg.grid_step = to_usize(int_field(key, v)?),
                "poc_win" => cfg.poc_win = to_usize(int_field(key, v)?),
                "max_disp" => cfg.max_disp = float_field(key, v)?,
                "poc_peak_min" => cfg.poc_peak_min = float_field(key, v)?,
                "median_thresh" => cfg.median_thresh = float_field(key, v)?,
                "lam" => cfg.lam = float_field(key, v)?,
                "scales" => cfg.scales = list_field(key, v)?,
                "n_orient" => cfg.n_orient = to_usize(int_field(key, v)?),
                "bandwidth" => cfg.bandwidth = float_field(key, v)?,
                "dc_cut" => cfg.dc_cut = float_field(key, v)?,
                "sigma_w" => cfg.sigma_w = float_field(key, v)?,
                "shape_order" => cfg.shape_order = to_u32(int_field(key, v)?),
                "sigma_s" => cfg.sigma_s = float_field(key, v)?,
                "outer_iters" => cfg.outer_iters = to_usize(int_field(key, v)?),
                "inner_iters" => cfg.inner_iters = to_usize(int_field(key, v)?),
                "conf_min" => cfg.conf_min = float_field(key, v)?,
                "edge_guard" => cfg.edge_guard = float_field(key, v)?,
                "edge_guard_min_area" => cfg.edge_guard_min_area = float_field(key, v)?,
                "phase_tol" => cfg.phase_tol = float_field(key, v)?,
                "strain_win" => cfg.strain_win = to_usize(int_field(key, v)?),
                "ref_update_conf" => cfg.ref_update_conf = float_field(key, v)?,
                "seq_mode" => cfg.seq_mode = str_field(key, v)?,
                "fb_max" => cfg.fb_max = to_i64(int_field(key, v)?),
                "fb_radius" => cfg.fb_radius = float_field(key, v)?,
                "fb_min_support" => cfg.fb_min_support = to_i64(int_field(key, v)?),
                "fb_tol" => cfg.fb_tol = float_field(key, v)?,
                "tavg" => cfg.tavg = to_i64(int_field(key, v)?),
                "tavg_align" => cfg.tavg_align = bool_field(key, v)?,
                "tavg_model" => cfg.tavg_model = str_field(key, v)?,
                "prewarp_freeze_at" => cfg.prewarp_freeze_at = to_i64(int_field(key, v)?),
                "crack_model" => cfg.crack_model = str_field(key, v)?,
                "xdic_RB" => cfg.xdic_rb = float_field(key, v)?,
                "xdic_iters" => cfg.xdic_iters = to_i64(int_field(key, v)?),
                // not reachable while the field list of this match and of the serde derive agree
                // (the tests check that every key serde writes is read); an error, never a panic
                other => return Err(ConfigError::UnknownKeys(vec![other.to_string()])),
            }
        }
        cfg.validate()?;
        Ok(cfg)
    }

    /// The text of Python's `to_json` (`json.dumps(..., indent=2)`): the same keys in the same
    /// order and layout, floats spelled like `float.__repr__` (`1e-07`, `0.0001`, `1e+16`), and
    /// `NaN`, `Infinity`, `-Infinity` for non-finite values (which `from_json` does not read).
    pub fn to_json(&self) -> String {
        // Destructuring without `..` makes a new field a compile error here until it is written.
        let Config {
            grid_step,
            poc_win,
            max_disp,
            poc_peak_min,
            median_thresh,
            lam,
            scales,
            n_orient,
            bandwidth,
            dc_cut,
            sigma_w,
            shape_order,
            sigma_s,
            outer_iters,
            inner_iters,
            conf_min,
            edge_guard,
            edge_guard_min_area,
            phase_tol,
            strain_win,
            ref_update_conf,
            seq_mode,
            fb_max,
            fb_radius,
            fb_min_support,
            fb_tol,
            tavg,
            tavg_align,
            tavg_model,
            prewarp_freeze_at,
            crack_model,
            xdic_rb,
            xdic_iters,
        } = self;
        let scales = if scales.is_empty() {
            "[]".to_string()
        } else {
            let items: Vec<String> = scales
                .iter()
                .map(|x| format!("    {}", json_float(*x)))
                .collect();
            format!("[\n{}\n  ]", items.join(",\n"))
        };
        let fields: [(&str, String); 30] = [
            ("grid_step", grid_step.to_string()),
            ("poc_win", poc_win.to_string()),
            ("max_disp", json_float(*max_disp)),
            ("poc_peak_min", json_float(*poc_peak_min)),
            ("median_thresh", json_float(*median_thresh)),
            ("lam", json_float(*lam)),
            ("scales", scales),
            ("n_orient", n_orient.to_string()),
            ("bandwidth", json_float(*bandwidth)),
            ("dc_cut", json_float(*dc_cut)),
            ("sigma_w", json_float(*sigma_w)),
            ("shape_order", shape_order.to_string()),
            ("sigma_s", json_float(*sigma_s)),
            ("outer_iters", outer_iters.to_string()),
            ("inner_iters", inner_iters.to_string()),
            ("conf_min", json_float(*conf_min)),
            ("edge_guard", json_float(*edge_guard)),
            ("edge_guard_min_area", json_float(*edge_guard_min_area)),
            ("phase_tol", json_float(*phase_tol)),
            ("strain_win", strain_win.to_string()),
            ("ref_update_conf", json_float(*ref_update_conf)),
            ("seq_mode", json_string(seq_mode)),
            ("fb_max", fb_max.to_string()),
            ("fb_radius", json_float(*fb_radius)),
            ("fb_min_support", fb_min_support.to_string()),
            ("fb_tol", json_float(*fb_tol)),
            ("tavg", tavg.to_string()),
            ("tavg_align", tavg_align.to_string()),
            ("tavg_model", json_string(tavg_model)),
            ("prewarp_freeze_at", prewarp_freeze_at.to_string()),
        ];
        // Python leaves the crack keys out while they have their default value
        let default = Config::default();
        let crack: [(&str, String, bool); 3] = [
            (
                "crack_model",
                json_string(crack_model),
                *crack_model == default.crack_model,
            ),
            (
                "xdic_RB",
                json_float(*xdic_rb),
                xdic_rb.to_bits() == default.xdic_rb.to_bits(),
            ),
            (
                "xdic_iters",
                xdic_iters.to_string(),
                *xdic_iters == default.xdic_iters,
            ),
        ];
        let lines: Vec<String> = fields
            .iter()
            .map(|(key, value)| (*key, value))
            .chain(crack.iter().filter(|c| !c.2).map(|c| (c.0, &c.1)))
            .map(|(key, value)| format!("  \"{key}\": {value}"))
            .collect();
        format!("{{\n{}\n}}", lines.join(",\n"))
    }
}

