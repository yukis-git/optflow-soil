    #[test]
    fn config_edge_guard_resolution() {
        let c = Config::default();
        let want = 3.0 * 8.0 * 1.6 / (2.0 * std::f64::consts::PI * 0.5);
        assert!((c.edge_guard_px() - want).abs() < 1e-12);
        assert_eq!(
            Config {
                edge_guard: 5.0,
                ..Config::default()
            }
            .edge_guard_px(),
            5.0
        );
        assert_eq!(
            Config {
                edge_guard: 0.0,
                ..Config::default()
            }
            .edge_guard_px(),
            0.0
        );
    }

    /// The automatic guard (3 spatial sigma of the longest filter) is what `edge_guard_px` resolves a
    /// negative `edge_guard` to, and it does not depend on the user's `edge_guard`: the pre-warp uses it
    /// whatever guard the user chose (spec 2.3).
    #[test]
    fn config_auto_edge_guard_is_independent_of_the_edge_guard() {
        let auto = Config::default().auto_edge_guard_px();
        assert!((auto - 3.0 * 8.0 * 1.6 / (2.0 * std::f64::consts::PI * 0.5)).abs() < 1e-12);
        assert!((auto - 12.2230).abs() < 1e-3);
        assert_eq!(Config::default().edge_guard_px(), auto);
        for edge_guard in [0.0, 5.0, 40.0] {
            let c = Config {
                edge_guard,
                ..Config::default()
            };
            assert_eq!(c.auto_edge_guard_px(), auto, "edge_guard {edge_guard}");
            assert_eq!(c.edge_guard_px(), edge_guard);
        }
        // follows lam, scales and bandwidth
        let c = Config {
            lam: 10.0,
            scales: vec![0.5, 2.0],
            bandwidth: 0.4,
            ..Config::default()
        };
        assert!(
            (c.auto_edge_guard_px() - 3.0 * 10.0 * 2.0 / (2.0 * std::f64::consts::PI * 0.4)).abs()
                < 1e-12
        );
    }

