#!/usr/bin/env python3
"""Writes rust/crates/optflow-core/src/config/unicode_cn.rs: the unassigned code points (general
category Cn) of this Python's Unicode database, which decide what `repr(str)` escapes.

    python/.venv/bin/python rust/scripts/gen_unicode_cn.py > rust/crates/optflow-core/src/config/unicode_cn.rs

Run it with the Python of the reference implementation; a Python with another Unicode version
gives other ranges (and the table test in config.rs, which counts them, must be updated).
"""
import sys
import unicodedata

ranges = []
start = None
for n in range(0x110000):
    cn = unicodedata.category(chr(n)) == "Cn"
    if cn and start is None:
        start = n
    elif not cn and start is not None:
        ranges.append((start, n - 1))
        start = None
if start is not None:
    ranges.append((start, 0x10FFFF))

total = sum(hi - lo + 1 for lo, hi in ranges)
out = sys.stdout
out.write(
    "//! Generated by `rust/scripts/gen_unicode_cn.py`; do not edit.\n"
    "//!\n"
    "//! The unassigned code points (general category Cn) of the Unicode database of Python\n"
    f"//! {sys.version.split()[0]} (Unicode {unicodedata.unidata_version}), as sorted, disjoint, "
    "inclusive ranges. Python's\n"
    "//! `repr(str)` escapes them; Rust's standard library has no category lookup.\n\n"
    f"/// {len(ranges)} ranges, {total} code points.\n"
    "#[rustfmt::skip]\n"
    f"pub(super) const UNASSIGNED: [(u32, u32); {len(ranges)}] = [\n"
)
line = "   "
for lo, hi in ranges:
    item = f" (0x{lo:04X}, 0x{hi:04X}),"
    if len(line) + len(item) > 100:
        out.write(line + "\n")
        line = "   "
    line += item
out.write(line + "\n];\n")
